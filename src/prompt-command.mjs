import { spawnSync } from "node:child_process";
import { realpath } from "node:fs/promises";
import path from "node:path";
import { placeLauncher, prepareDeployment } from "./distribution.mjs";
import { codexHome } from "./runtime.mjs";
import { targetHost, remoteTransport } from "./target.mjs";

export const SUPERVISOR_AGENTS = ["claude", "codex"];
const BOUND_OPTIONS = ["--require-node-version", "--supervisor", "--connection", "--host", "--remote-transport", "--context-thread"];

// Parsers take the first occurrence, so a repeated option would silently
// change or bypass the binding of a generated command.
export function rejectRepeatedBinding(argv) {
  const own = argv.includes("--") ? argv.slice(0, argv.indexOf("--")) : argv;
  const repeated = BOUND_OPTIONS.find(name => own.indexOf(name) !== own.lastIndexOf(name));
  if (repeated) throw Object.assign(new Error(`Specify ${repeated} only once. A generated supervision command already sets it; run that command without adding it again.`), { code: "OPTIONS_INVALID" });
}

export function shellArgument(value) {
  if (/[\u0000-\u001f\u007f-\u009f\u2028\u2029]/u.test(value)) {
    throw Object.assign(new Error("Cannot generate supervision commands from a path containing control characters. Use a path without them and generate the prompt again."), { code: "SUPERVISION_PATH_UNSAFE" });
  }
  return `'${value.replaceAll("'", "'\\''")}'`;
}

const shellWord = value => /^[A-Za-z0-9_./-]+$/.test(value) ? value : shellArgument(value);

function bindingArguments({ session, connection, context }) {
  const host = targetHost();
  return [
    ...(session ? ["--supervisor", shellArgument(session)] : []),
    "--connection", connection,
    ...(host === "local" ? [] : ["--host", shellArgument(host), "--remote-transport", remoteTransport(), ...(context ? ["--context-thread", shellArgument(context)] : [])]),
  ];
}

// A session binding is one supervisor's; a project binding (session null)
// only creates threads and child prompts. Saved mode bakes the whole binding
// into a launcher, so the prompt shows one word an agent cannot partly drop.
export async function prepareBoundCommand(binding, usePathCli = false) {
  const options = bindingArguments(binding);
  if (usePathCli) return { command: ["codexteer", ...options].join(" "), cli_mode: "path", deployment: null, node: null };
  const node = { path: await realpath(process.execPath), version: process.version };
  const home = codexHome();
  shellArgument(node.path); shellArgument(home);
  const deployment = await prepareDeployment(home);
  const cli = path.join(deployment.directory, "bin/codexteer.mjs");
  const script = `#!/bin/sh
# Generated by codexteer for one supervision binding. Do not edit; generate the prompt again instead.
CODEX_HOME=${shellArgument(deployment.codex_home)}
export CODEX_HOME
exec ${shellArgument(node.path)} ${shellArgument(cli)} --require-node-version ${shellArgument(node.version)} ${options.join(" ")} "$@"
`;
  const launcher = await placeLauncher(deployment, binding.session ? "s" : "p", script);
  // A home mounted noexec or a sandbox that denies exec there would otherwise
  // surface only when the agent runs its first command.
  const probe = spawnSync(launcher, ["--version"], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 30000 });
  if (probe.error || probe.status !== 0 || probe.stdout.trim() !== deployment.version) {
    const reason = probe.error?.code ?? (probe.stderr.trim().split("\n")[0] || `exit status ${probe.status}`);
    throw Object.assign(new Error(`The generated launcher ${launcher} cannot run here (${reason}). Generate the prompt where files under CODEX_HOME may be executed, or use --use-path-cli.`), { code: "LAUNCHER_UNUSABLE" });
  }
  return { command: shellWord(launcher), cli_mode: "saved", deployment, node };
}
